import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { groupAnswerEntries } from "../src/answerComposition.ts";
import { applyPresentationDelta, mergePresentationSnapshot } from "../src/presentationHydration.ts";
const corpus = JSON.parse(readFileSync(new URL("../../vak-delivery/tests/fixtures/rich-answer.json", import.meta.url)));
const expected = ["leading", "chart-entry", "between", "numbers", "sources-entry"];
const groups = groupAnswerEntries(corpus.items.map(item => ({ item })));
assert.deepEqual(groups.filter(group => group.kind === "result").flatMap(group => group.entries.map(entry => entry.item.id)), expected);
let current = mergePresentationSnapshot(null, corpus);
assert.deepEqual(current.items, corpus.items);
current = applyPresentationDelta(current, { type: "item_removed", item_id: "leading" });
assert.ok(!current.items.some(item => item.id === "leading"));
assert.equal(current.items.find(item => item.id === "numbers").content.document.source_markdown.includes("12345678901234567890.001"), true);
const late = structuredClone(corpus.items[2]);
late.outcome = null;
late.provenance.source = "live_event";
current = applyPresentationDelta(current, { type: "item_replaced", item: late });
assert.equal(current.items.find(item => item.id === late.id).outcome.status, "partial");
console.log("shared rich-answer corpus retains order, scalars, removal and settled verdicts");
