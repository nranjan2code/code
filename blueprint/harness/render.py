# The HTML's tabs, in order, and the sheets (section ids) each holds.
TABS = [
    ("overview", "Overview", ["summary", "attention", "happening", "record"]),
    ("system", "System", ["layers", "processes", "turn", "data"]),
    ("inventory", "Inventory", ["bom", "size", "work"]),
    ("findings", "Findings", ["findings", "target"]),
]


def navigation(template):
    """Tag each sheet with its tab, and draw the tabs and the left panel."""
    group = {sid: g for g, _, ids in TABS for sid in ids}
    titles = dict(re.findall(r'<section class="sheet" id="([^"]+)">\s*<header><span class="sno">Sheet[^<]*</span><h2>([^<]+)</h2>', template))
    unplaced = [sid for sid in titles if sid not in group]
    template = re.sub(r'<section class="sheet" id="([^"]+)">',
                      lambda m: f'<section class="sheet" id="{m.group(1)}" data-group="{group.get(m.group(1), TABS[0][0])}">', template)
    order = list(titles)
    tabs = '<nav class="tabs" role="tablist" aria-label="Blueprint tabs">' + "".join(
        f'<button type="button" role="tab" id="tab-{g}" data-group="{g}" data-first="{ids[0]}" aria-selected="{"true" if i == 0 else "false"}">{esc(name)}</button>'
        for i, (g, name, ids) in enumerate(TABS)) + "</nav>"
    toc = "".join(
        f'<a href="#{sid}" data-group="{group.get(sid, TABS[0][0])}"{"" if group.get(sid, TABS[0][0]) == TABS[0][0] else " hidden"}>'
        f'<span class="n">{order.index(sid) + 1:02d}</span>{esc(titles[sid])}</a>' for sid in order)
    template = template.replace("%%NAV%%", tabs).replace("%%TOC%%", toc)
    # sheets outside the first tab start hidden, so the page is complete at rest
    template = re.sub(r'(<section class="sheet" id="[^"]+" data-group="(?!' + TABS[0][0] + r')[^"]+")>', r"\1 hidden>", template)
    return template, unplaced


