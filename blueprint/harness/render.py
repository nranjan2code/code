# ---- Markdown helpers -------------------------------------------------------

def md_inline_to_html(text):
    out = html.escape(text, quote=False)
    out = re.sub(r"`([^`]+)`", r"<code>\1</code>", out)
    out = re.sub(r"\*\*([^*]+)\*\*", r"<b>\1</b>", out)
    out = re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", lambda m: f'<a href="{_html_href(m.group(2))}">{m.group(1)}</a>', out)
    return out


def _html_href(href):
    # content.toml links are relative to blueprint/, as README.md and blueprint.html are
    return href


def md_to_html(text):
    """Paragraphs and "- " lists, the only block forms content.toml uses."""
    blocks, para, items = [], [], []

    def flush():
        if para:
            blocks.append(f"<p>{md_inline_to_html(' '.join(para))}</p>")
            para.clear()
        if items:
            blocks.append('<ul class="plain">' + "".join(f"<li>{md_inline_to_html(i)}</li>" for i in items) + "</ul>")
            items.clear()
    for line in text.split("\n"):
        if line.startswith("- "):
            if para:
                flush()
            items.append(line[2:].strip())
        elif not line.strip():
            flush()
        else:
            if items:
                flush()
            para.append(line.strip())
    flush()
    return "\n".join(blocks)


def esc(s):
    return html.escape(str(s))


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


