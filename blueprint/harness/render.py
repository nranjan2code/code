def page(model, resolve):
    template = open(ms.TEMPLATE, encoding="utf-8").read()
    template = template.replace("../docs/brand/exports/vakyartha-songbird-reverse.svg", logo_uri("reverse"))
    template = template.replace("../docs/brand/exports/vakyartha-songbird-colour.svg", logo_uri("colour"))
    files, fns, cc = size_tables(model)
    blocks = {
        "SUMMARY": md_to_html(model["summary"]["text"]),
        "ATTENTION": attention_html(model), "ACTIVITY": activity_html(model), "DECISIONS": decisions_html(model),
        "LAYER_SVG": layer_svg(model, model["work"]["hot"]), "MATRIX": matrix(model), "UPWARD": upward_list(model),
        "BOM": bom(model), "FILTERS": filters(model), "WORK": work_bars(model),
        "TOP_FILES": files, "TOP_FNS": fns, "TOP_CC": cc,
        "FINDINGS": findings_html(model), "KEEP": keep_html(model), "TARGET": md_to_html(model["target"]),
        "TOOLS": ", ".join(f"<code>{esc(t)}</code>" for t in model["summary"]["tools"]),
    }
    for key, val in blocks.items():
        template = template.replace("%%" + key + "%%", val)
    template = resolve(template)
    # sheets are numbered in page order, and the title block lists them
    n = iter(range(1, 100))
    template = re.sub(r'<span class="sno">Sheet</span>', lambda _: f'<span class="sno">Sheet {next(n):02d}</span>', template)
    template, unplaced = navigation(template)
    model["review"].extend(f"sheet {sid} is in no tab (render.TABS)" for sid in unplaced)
    banner = ""
    if model["review"]:
        banner = '<section class="banner" role="status"><b>Needs review.</b> ' + "; ".join(esc(r) for r in model["review"]) + '. See <code>blueprint/AGENTS.md</code>.</section>'
    return template.replace("%%REVIEW%%", banner)


