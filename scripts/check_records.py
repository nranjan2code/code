#!/usr/bin/env python3
"""Checks that the project's record is one place per kind of fact, and current.

docs/README.md says what each file is for. This script enforces the parts a
machine can check, for people and agents alike:

1. Every design doc (docs/design/*.md) and every plan (docs/plans/*.md but
   the handover and the tracker) has a `Status:` line whose first word is
   one of STATUS_WORDS, so "is this built?" is answered the same way
   everywhere.
2. docs/design/INDEX.md is exactly what this script generates from those
   lines. Regenerate it with `python3 scripts/check_records.py --write`;
   never edit it by hand.
3. There is exactly one handover, docs/plans/handover-*.md, and the tracker
   docs/plans/open-items.md and the decision log docs/decisions.md exist.
4. CHANGELOG.md starts with `## Unreleased`, and once code under crates/ has
   changed since the newest release tag it has at least one entry there.

Exit status 1 names every failure.
"""

import glob
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DESIGN = os.path.join(ROOT, "docs", "design")
INDEX = os.path.join(DESIGN, "INDEX.md")

# What a design doc is, in one word or two. The rest of the Status line says
# what of it is built, what is not, and why.
STATUS_WORDS = [
    "proposal",  # a design not yet built; its paths are targets
    "in progress",  # partly built; the line says which parts
    "implemented",  # built; the line names anything cut by decision
    "reference",  # describes shipped code or how to work on it
    "superseded",  # replaced; the line names what replaced it
    "historical",  # a record of the past, kept as it was
]

STATUS = re.compile(r"^Status:\s*(.*)$", re.MULTILINE)
TITLE = re.compile(r"^#\s+(.*)$", re.MULTILINE)


def status_word(text):
    """The doc's status word, or None when its Status line has none."""
    match = STATUS.search(text)
    if not match:
        return None
    lead = match.group(1).lower().lstrip("*_ ")
    for word in STATUS_WORDS:
        if lead.startswith(word):
            return word
    return None


def status_line(text):
    """The Status paragraph as one line, without emphasis marks."""
    match = STATUS.search(text)
    if not match:
        return ""
    start = match.start(1)
    end = text.find("\n\n", start)
    para = text[start : end if end != -1 else len(text)]
    para = " ".join(para.split()).replace("**", "")
    return para


def summary(para, word):
    """The Status paragraph's first sentence after its status word."""
    rest = para[len(word) :].lstrip(" .;:,—-")
    sentence = re.split(r"(?<=[.;])\s", rest, maxsplit=1)[0]
    return sentence.rstrip(".;") if sentence else ""


def design_docs():
    for path in sorted(glob.glob(os.path.join(DESIGN, "*.md"))):
        if os.path.basename(path) == "INDEX.md":
            continue
        yield path


def plan_docs():
    for path in sorted(glob.glob(os.path.join(ROOT, "docs", "plans", "*.md"))):
        name = os.path.basename(path)
        if name.startswith("handover-") or name == "open-items.md":
            continue
        yield path


def build_index():
    rows = []
    for path in design_docs():
        text = open(path, encoding="utf-8").read()
        title = TITLE.search(text)
        word = status_word(text) or "?"
        para = status_line(text)
        rows.append(
            (
                os.path.basename(path),
                (title.group(1).strip() if title else os.path.basename(path)),
                word,
                summary(para, word) if word != "?" else para[:120],
            )
        )
    counts = {word: sum(1 for r in rows if r[2] == word) for word in STATUS_WORDS}
    out = [
        "# Design docs index",
        "",
        "Generated by `python3 scripts/check_records.py --write` from each",
        "document's `Status:` line; never edit it by hand. The status word says",
        "what a document is; open the document for the whole Status line.",
        "Open work across all of them is `docs/plans/open-items.md`.",
        "",
        "Counts: "
        + ", ".join(f"{counts[w]} {w}" for w in STATUS_WORDS if counts[w])
        + ".",
        "",
        "| Doc | Title | Status | Summary |",
        "|---|---|---|---|",
    ]
    for name, title, word, text in rows:
        cell = text.replace("|", "\\|")
        out.append(f"| [{name}]({name}) | {title} | {word} | {cell} |")
    return "\n".join(out) + "\n"


def changelog_problems():
    path = os.path.join(ROOT, "CHANGELOG.md")
    text = open(path, encoding="utf-8").read()
    headings = re.findall(r"^## (.*)$", text, re.MULTILINE)
    cargo = open(os.path.join(ROOT, "Cargo.toml"), encoding="utf-8").read()
    version = re.search(r'^version = "([^"]+)"', cargo, re.MULTILINE).group(1)
    first = headings[0].strip() if headings else ""
    # A release commit names its own section (scripts/release.sh requires it).
    if first != "Unreleased" and first.split(" ", 1)[0] != version:
        return [
            "CHANGELOG.md: the first section must be `## Unreleased`, "
            f"or `## {version} — <date>` in the commit that releases it"
        ]
    body = text.split(f"## {first}", 1)[1].split("\n## ", 1)[0]
    entries = [line for line in body.splitlines() if line.startswith("- ")]
    try:
        tag = subprocess.run(
            ["git", "describe", "--tags", "--abbrev=0", "--match", "v*"],
            cwd=ROOT,
            capture_output=True,
            text=True,
            check=True,
        ).stdout.strip()
        changed = subprocess.run(
            ["git", "diff", "--quiet", tag, "HEAD", "--", "crates"],
            cwd=ROOT,
        ).returncode
    except (subprocess.CalledProcessError, FileNotFoundError):
        return []
    if changed and not entries:
        return [
            f"CHANGELOG.md: code changed since {tag} and `## {first}` has no entry"
        ]
    return []


def main():
    write = "--write" in sys.argv[1:]
    problems = []
    for path in [*design_docs(), *plan_docs()]:
        text = open(path, encoding="utf-8").read()
        if status_word(text) is None:
            problems.append(
                f"{os.path.relpath(path, ROOT)}: Status must start with one of: "
                + ", ".join(STATUS_WORDS)
            )
    index = build_index()
    if write:
        open(INDEX, "w", encoding="utf-8").write(index)
    elif not os.path.exists(INDEX) or open(INDEX, encoding="utf-8").read() != index:
        problems.append(
            "docs/design/INDEX.md is stale: run `python3 scripts/check_records.py --write`"
        )
    handovers = glob.glob(os.path.join(ROOT, "docs", "plans", "handover-*.md"))
    if len(handovers) != 1:
        problems.append(
            f"docs/plans: {len(handovers)} handovers; keep exactly one (git keeps the rest)"
        )
    for required in ("docs/README.md", "docs/plans/open-items.md", "docs/decisions.md"):
        if not os.path.exists(os.path.join(ROOT, required)):
            problems.append(f"{required} is missing")
    problems += changelog_problems()
    if problems:
        print(f"FAIL: {len(problems)} record problem(s):")
        for problem in problems:
            print(" ", problem)
        sys.exit(1)
    print("records ok")


if __name__ == "__main__":
    main()
